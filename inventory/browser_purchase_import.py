        output.mkdir(parents=True, exist_ok=True)
        with sync_playwright() as playwright:
            browser = playwright.chromium.launch(channel=os.getenv('PURCHASE_IMPORT_BROWSER_CHANNEL', 'msedge'), headless=True)
